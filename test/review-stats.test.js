// The counts behind agent-standup.com/review/ (website/src/review-stats.js), on a made-up transcript.
const test = require('node:test'), assert = require('node:assert');
const { reviewStats } = require('../website/src/review-stats.js');

const at = (h, m = 0) => new Date(2026, 9, 14, h, m).toISOString();
const user = (uuid, ts, content, extra) => JSON.stringify({ type: 'user', uuid, timestamp: ts, sessionId: 's1', message: { role: 'user', content }, ...extra });
const said = (uuid, ts, id, blocks, usage) => JSON.stringify({ type: 'assistant', uuid, timestamp: ts, sessionId: 's1', message: { id, role: 'assistant', content: blocks, usage } });

test('counts prompts, phrases, interruptions and sub-agents, and skips what the person did not type', () => {
  const st = reviewStats();
  st.open('projects/-Users-me-app/s1.jsonl');
  [
    user('u1', at(23, 50), 'please fix the login bug, thanks'),
    said('a1', at(23, 51), 'm1', [{ type: 'text', text: 'You’re absolutely right! Let me look.' }], { output_tokens: 10 }),
    said('a2', at(23, 51), 'm1', [{ type: 'tool_use', id: 't1', name: 'Task', input: {} }], { output_tokens: 10 }),   // same message id: its tokens count once
    JSON.stringify({ type: 'user', uuid: 'r1', timestamp: at(23, 52), message: { content: [{ type: 'tool_result', tool_use_id: 't1', content: 'ok' }] } }),
    user('u2', at(3, 47), '[Request interrupted by user]'),
    user('u3', at(3, 47), 'yes'),
    user('u4', at(3, 48), '<command-name>/clear</command-name>'),
    user('u5', at(3, 48), 'Caveat: the messages below were generated by the user while running local commands.', { isMeta: true }),
    user('u3', at(3, 47), 'yes'),   // a resumed copy of the same record
    said('a3', at(3, 49), 'm2', [{ type: 'text', text: 'You are right, sorry about that. wtf indeed.' }]),
    user('u6', at(3, 50), 'WTF WHY DID YOU DELETE THE TESTS'),
    'not json',
  ].forEach((l) => st.add(l));
  st.open('projects/-Users-me-app/s1/subagents/agent-abc.jsonl');
  st.add(user('u7', at(23, 52), 'Audit the login flow'));   // the lead's task for the sub-agent, not the person's prompt
  st.add(said('a4', at(23, 53), 'm3', [{ type: 'text', text: 'You’re absolutely right' }]));
  const r = st.result();
  assert.equal(r.prompts, 3);
  assert.equal(r.esc, 1);
  assert.deepEqual(r.slash, [['/clear', 1]]);
  assert.equal(r.ar, 1);
  assert.equal(r.right, 1);
  assert.equal(r.please, 1); assert.equal(r.thanks, 1);
  assert.deepEqual(r.short, [['yes', 1]]);
  assert.equal(r.caps, 1);
  assert.deepEqual(r.swears, [['wtf', 1]]);
  assert.equal(r.night, 2);
  assert.equal(new Date(r.latest).getHours(), 3);
  assert.equal(r.outTokens, 10);
  assert.equal(r.spawned, 1); assert.equal(r.subFiles, 1);
  assert.equal(r.projects, 1); assert.equal(r.sessions, 1);
  assert.equal(r.peak, 2);   // the lead and its sub-agent in the same minute
});
